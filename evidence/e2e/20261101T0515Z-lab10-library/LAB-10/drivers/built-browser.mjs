  events.push({label:label+'-raw',http:response.status,type:response.type,body:response.text});
  let body;
  if(response.status===401)body=JSON.parse(response.text);
  else {const decoded=fromCrossJSON(JSON.parse(response.text),{plugins:[]});body=decoded.result;assert.ok(body&&typeof body.ok==='boolean',JSON.stringify({label,keys:Object.keys(decoded)}));}
